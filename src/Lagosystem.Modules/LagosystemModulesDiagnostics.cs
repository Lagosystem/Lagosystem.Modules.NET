

namespace Lagosystem.Modules
{
    using System;
    using System.Diagnostics;
    using System.Runtime.ExceptionServices;
    using System.Threading;
    using System.Runtime.CompilerServices;
    using Modules.LanguagesResource;

    /// <summary>
    /// Provides centralized diagnostic and telemetry capabilities for the Lagosystem modules.
    /// Allows for custom error and warning handling, as well as debugging configurations.
    /// </summary>
    /// <remarks>
    /// This class is designed to be thread-safe using <see cref="Volatile"/> operations for reading and writing handlers.
    /// </remarks>
    public static class Diagnostics
    {
        private static readonly ConditionalWeakTable<Exception, object> ReportedOperationalErrors = new();

        /// <summary>Reports environmental failures once; caller mistakes and cancellation are excluded.</summary>
        internal static bool ReportOperationalFailure(Exception exception, string methodName, string className)
        {
            if (exception is not (System.IO.IOException or UnauthorizedAccessException or System.Security.SecurityException or System.Net.Http.HttpRequestException or System.Net.Sockets.SocketException)) return false;
            lock (ReportedOperationalErrors)
            {
                if (ReportedOperationalErrors.TryGetValue(exception, out _)) return true;
                ReportedOperationalErrors.Add(exception, new object());
            }
            ReportError(methodName, className, exception, "An environmental operation failed.");
            return true;
        }
        private static OnAnyErrorEventHandle? _onAnyError;
        private static OnAnyWarningEventHandle? _onAnyWarning;
        private static bool _throwInDebugMode = true;

        /// <summary>Gets or sets a value indicating whether exceptions should be re-thrown when the application is running in DEBUG mode.</summary>
        /// <value>
        /// <see langword="true"/> to re-throw exceptions to the debugger;
        /// otherwise, <see langword="false"/> to let the library control handling in debugger sessions.
        /// </value>
        [DebuggerDisplay("{ThrowInDebugMode,nq}")]
        public static bool ThrowInDebugMode
        {
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => Volatile.Read(ref _throwInDebugMode);
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set => Volatile.Write(ref _throwInDebugMode, value);
        }

        /// <summary>Registers a custom handler to intercept and process errors generated by the library.</summary>
        /// <param name="handle">The callback method that will be invoked when an error occurs.</param>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static void SetErrorHandler(OnAnyErrorEventHandle? handle) => Volatile.Write(ref _onAnyError, handle);

        /// <summary>Registers a custom handler to intercept and process warnings generated by the library.</summary>
        /// <param name="handle">The callback method that will be invoked when a warning occurs.</param>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static void SetWarningHandler(OnAnyWarningEventHandle? handle) => Volatile.Write(ref _onAnyWarning, handle);

        /// <summary>Clears all registered diagnostic handlers (errors and warnings), setting them to <see langword="null"/>.</summary>
        public static void Clear()
        {
            Volatile.Write(ref _onAnyError, null);
            Volatile.Write(ref _onAnyWarning, null);
        }

        /// <summary>Reports an error internally, invoking the registered error handler and logging the details to the debug console.</summary>
        /// <param name="methodName">The name of the method where the error occurred.</param>
        /// <param name="className">The name of the class where the error occurred.</param>
        /// <param name="exception">The captured exception, if any.</param>
        /// <param name="message">An optional contextual error message.</param>
        /// <remarks>
        /// If a callback throws an exception, it is caught and safely written to the debug console to prevent crashing the application.
        /// If compiled in DEBUG mode and <see cref="ThrowInDebugMode"/> is <see langword="true"/>, the exception is re-thrown preserving its stack trace.
        /// </remarks>
        internal static void ReportError(string methodName, string className, Exception? exception, string? message = null)
        {
            OnAnyErrorEventHandle? callback = Volatile.Read(ref _onAnyError);

            if (callback != null)
                try { callback.Invoke(methodName, className, exception, message); }
                catch (Exception ex) { WriteDebugCallbackError(nameof(ReportError), typeof(Diagnostics).FullName ?? nameof(Diagnostics), ex); }

            WriteDebugError(methodName, className, exception, message);

            if (Debugger.IsAttached && ThrowInDebugMode && exception != null) ExceptionDispatchInfo.Capture(exception).Throw();
        }

        /// <summary>Reports a warning internally, invoking the registered warning handler and logging the details to the debug console.</summary>
        /// <param name="methodName">The name of the method where the warning occurred.</param>
        /// <param name="className">The name of the class where the warning occurred.</param>
        /// <param name="message">The warning message detailing the issue.</param>
        /// <remarks>If a callback throws an exception, it is caught and safely written to the debug console.</remarks>
        internal static void ReportWarning(string methodName, string className, string message)
        {
            OnAnyWarningEventHandle? callback = Volatile.Read(ref _onAnyWarning);
            if (callback != null)
                try { callback.Invoke(methodName, className, message); }
                catch (Exception ex) { WriteDebugCallbackError(nameof(ReportWarning), typeof(Diagnostics).FullName ?? nameof(Diagnostics), ex); }
            WriteDebugWarning(methodName, className, message);
        }

        /// <summary>
        /// Writes detailed error diagnostic information to the standard debug output.
        /// This method is only compiled into the build if the "DEBUG" symbol is defined.
        /// </summary>
        [Conditional("DEBUG")]
        private static void WriteDebugError(string methodName, string className, Exception? exception, string? message)
        {
            string exceptionType = exception?.GetType().FullName ?? "No exception";
            string exceptionMessage = exception?.Message ?? "No exception message";
            string exceptionStackTrace = exception?.StackTrace ?? "No stack trace";

            Debug.WriteLine(
                $"{ExceptionsResource.ErrorMessageReportError}{Environment.NewLine}" +
                $"Class: {className}{Environment.NewLine}" +
                $"Method: {methodName}{Environment.NewLine}" +
                $"Message: {message ?? "No message"}{Environment.NewLine}" +
                $"Exception Type: {exceptionType}{Environment.NewLine}" +
                $"Exception Message: {exceptionMessage}{Environment.NewLine}" +
                $"StackTrace: {exceptionStackTrace}");
        }

        /// <summary>
        /// Writes detailed error diagnostic information to the standard debug output.
        /// This method is only compiled into the build if the "DEBUG" symbol is defined.
        /// </summary>
        [Conditional("DEBUG")]
        private static void WriteDebugWarning(string methodName, string className, string message) =>
            Debug.WriteLine($"""
                             Warning reported.{Environment.NewLine}
                             Class: {className}{Environment.NewLine}
                             Method: {methodName}{Environment.NewLine}
                             Message: {message}
                             """);

        /// <summary>
        /// Safely logs errors that occur *within* the user-defined diagnostic callbacks to prevent infinite crash loops.
        /// This method is only compiled into the build if the "DEBUG" symbol is defined.
        /// </summary>
        [Conditional("DEBUG")]
        private static void WriteDebugCallbackError(string methodName, string className, Exception exception) =>
            Debug.WriteLine($"""
                             Diagnostics callback failed.{Environment.NewLine}
                             Class: {className}{Environment.NewLine}
                             Method: {methodName}{Environment.NewLine}
                             Exception Type: {exception.GetType().FullName}{Environment.NewLine}
                             Exception Message: {exception.Message}{Environment.NewLine}
                             StackTrace: {exception.StackTrace}
                             """);
    }

    /// <summary>
    /// Represents a delegate used to handle and report any errors or exceptions that occur within the application or library.
    /// </summary>
    /// <param name="methodName">The name of the method where the error originated.</param>
    /// <param name="className">The full or short name of the class where the error originated.</param>
    /// <param name="exception">The exception that was caught, or <see langword="null"/> if the error is not tied to a specific exception.</param>
    /// <param name="message">An optional custom message providing additional context about the error.</param>
    public delegate void OnAnyErrorEventHandle(string methodName, string className, Exception? exception, string? message);

    /// <summary>
    /// Represents a delegate used to handle and report non-critical warnings that occur within the application or library.
    /// </summary>
    /// <param name="methodName">The name of the method where the warning was triggered.</param>
    /// <param name="className">The full or short name of the class where the warning was triggered.</param>
    /// <param name="message">The warning message providing context about the non-critical issue.</param>
    public delegate void OnAnyWarningEventHandle(string methodName, string className, string message);
}


